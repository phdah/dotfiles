local lib = require("phdah.plugins.lib")

lib.eager({ "gitsigns.nvim" })
require("gitsigns").setup()

vim.keymap.set("n", "gu", function()
    require("gitsigns").reset_hunk()
end, { desc = "(g)it (u)undo", silent = true })
vim.keymap.set("n", "gU", function()
    require("gitsigns").undo_stage_hunk()
end, { desc = "(g)it (U)undo staged hunk", silent = true })
vim.keymap.set("n", "gd", function()
    require("gitsigns").preview_hunk()
end, { desc = "(g)it (d)iff", silent = true })
vim.keymap.set("n", "gD", function()
    require("gitsigns").diffthis()
end, { desc = "(g)it (d)iff this file", silent = true })
vim.keymap.set("n", "gs", function()
    require("gitsigns").stage_hunk()
end, { desc = "(g)it (s)tage", silent = true })
vim.keymap.set("v", "gs", function()
    lib.exit_visual()
    require("gitsigns").stage_hunk({ vim.fn.line("'<"), vim.fn.line("'>") })
end, { desc = "(g)it (s)tage", silent = true })
vim.keymap.set("n", "gb", function()
    require("gitsigns").blame_line()
end, { desc = "(g)it (b)lame", silent = true })
